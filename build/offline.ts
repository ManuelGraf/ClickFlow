import { createHash } from 'node:crypto'
import { readdirSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'
import type { Plugin } from 'vite'

const SW_FILE = 'sw.js'

function listFiles(dir: string, root = dir): string[] {
  let out: string[] = []
  for (const name of readdirSync(dir)) {
    const full = join(dir, name)
    if (statSync(full).isDirectory()) out = out.concat(listFiles(full, root))
    else out.push(relative(root, full).split('\\').join('/'))
  }
  return out
}

// Emits a small precaching service worker so the app keeps working offline once
// it has loaded. Deliberately hand-rolled rather than workbox: the app is one
// bundle plus a few static files, so the whole policy fits on one screen.
//
// - Install precaches every emitted file and every public/ file.
// - Navigations are network-first (fresh deploys win while online) and fall back
//   to the precached index.html when offline.
// - Everything else is cache-first; asset names are content-hashed.
// - The cache name is a hash of the emitted contents, so each deploy gets a new
//   cache and the previous one is deleted once the new worker activates.
// The worker only ever requests the app's own static files — never user data,
// which lives in IndexedDB and is not touched here.
export function offline(): Plugin {
  let publicDir = ''
  return {
    name: 'clickflow-offline',
    apply: 'build',
    enforce: 'post',
    configResolved(config) {
      publicDir = config.publicDir
    },
    generateBundle(_options, bundle) {
      const hash = createHash('sha256')
      const files = Object.keys(bundle).sort()
      for (const name of files) {
        const item = bundle[name]!
        hash.update(name)
        hash.update(item.type === 'chunk' ? item.code : item.source)
      }
      let publicFiles: string[] = []
      try {
        publicFiles = listFiles(publicDir)
      } catch {
        // No public dir — nothing extra to precache.
      }
      for (const name of publicFiles) hash.update(name)

      const precache = ['./', ...files, ...publicFiles].filter((f) => f !== SW_FILE)
      const version = hash.digest('hex').slice(0, 12)
      this.emitFile({ type: 'asset', fileName: SW_FILE, source: workerSource(version, precache) })
    },
  }
}

function workerSource(version: string, precache: string[]): string {
  return `// Generated by build/offline.ts — do not edit.
const CACHE = 'clickflow-${version}'
const PRECACHE = ${JSON.stringify(precache)}
const INDEX = new URL('./', self.location).href
// Hosts add Vary headers (Origin, Accept-Encoding) that differ between the
// install-time fetch and the page's own requests; assets are content-hashed,
// so matching on URL alone is safe.
const MATCH = { ignoreSearch: true, ignoreVary: true }

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)))
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys.filter((k) => k.startsWith('clickflow-') && k !== CACHE).map((k) => caches.delete(k)),
        ),
      )
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('fetch', (event) => {
  const request = event.request
  if (request.method !== 'GET') return
  if (new URL(request.url).origin !== self.location.origin) return

  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request).catch(() =>
        caches.open(CACHE).then((cache) => cache.match(INDEX, MATCH)).then((hit) => hit || Response.error()),
      ),
    )
    return
  }

  event.respondWith(
    caches
      .open(CACHE)
      .then((cache) => cache.match(request, MATCH))
      .then((hit) => hit || fetch(request)),
  )
})
`
}
